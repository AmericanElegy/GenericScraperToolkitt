import {build} from 'esbuild';
import {readFile,writeFile,readdir} from 'node:fs/promises';
// Bundle browser-only parsers as same-origin resources. No CDN or paid service.
export async function buildToolkit() {
  const result=await build({entryPoints:['src/interpretation/file-import.js'],bundle:true,format:'iife',platform:'browser',minify:true,write:false,metafile:true});
  const pdf=await readFile('node_modules/pdfjs-dist/build/pdf.worker.min.mjs','utf8');
  await writeFile('src/interpretation/file-assets.js',`// Generated by scripts/build.mjs.\nexport const fileClient=${JSON.stringify(result.outputFiles[0].text)};\nexport const pdfWorker=${JSON.stringify(pdf)};\n`);
  await build({entryPoints:['src/worker.js'],bundle:true,format:'esm',platform:'browser',loader:{'.txt':'text'},outfile:'worker-code.txt'});
  const packages=new Set(['node_modules/entities','node_modules/pdfjs-dist','node_modules/jose']);
  for(const input of Object.keys(result.metafile.inputs))if(input.startsWith('node_modules/')){
    const parts=input.split('/');packages.add(parts.slice(0,parts[1].startsWith('@')?3:2).join('/'));
  }
  let notices='Bundled third-party software. Generated by scripts/build.mjs.\n';
  for(const path of [...packages].sort()){
    const pkg=JSON.parse(await readFile(path+'/package.json','utf8'));
    notices+='\n\n'+pkg.name+' '+pkg.version+' · '+pkg.license+'\n';
    for(const name of (await readdir(path)).filter(n=>/^(licen[sc]e|notice)(\.|$)/i.test(n)).sort())notices+='\n'+await readFile(path+'/'+name,'utf8')+'\n';
  }
  await writeFile('THIRD_PARTY_NOTICES.txt',notices.replace(/[ \t]+$/gm,'').trimEnd()+'\n');
}
if(process.argv[1] && new URL(import.meta.url).pathname.endsWith(process.argv[1].replaceAll('\\','/').split('/').pop())) await buildToolkit();
